_PLACEHOLDER_RE = re.compile(r"\{([a-zA-Z_][a-zA-Z0-9_]*)\}")


def available_languages() -> tuple:
    return LANGUAGES


def is_rtl(language: str) -> bool:
    """True when the language needs a right-to-left layout."""
    return language in _RTL_LANGUAGES


def tr(language: str, key: str, **kwargs) -> str:
    """Look up a string; fall back to French, then to the key itself."""
    text = _STRINGS.get(language, {}).get(key) or _STRINGS["fr"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text


def state_label(language: str, state: str) -> str:
    """Localised label for a workflow state; unknown states pass through.

    The server owns the state machine. If it starts returning a state this
    catalogue does not know, the raw identifier is shown rather than a
    misleading guess.
    """
    key = STATE_KEYS.get(str(state))
    return tr(language, key) if key else str(state or "")


def keys() -> Tuple[str, ...]:
    """Every catalogue key (used by the parity test)."""
    return tuple(sorted(_FR))


def placeholders(text: str) -> Tuple[str, ...]:
    """Named placeholders in a template, for the placeholder-parity test."""
    return tuple(sorted(_PLACEHOLDER_RE.findall(text)))


