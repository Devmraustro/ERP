"""French, Arabic and English user-facing strings for the desktop client.

Algerian businesses work in French and Arabic (often both in the same office)
and increasingly in English with international suppliers, so Phase 29 ships
the three from day one and the layout direction flips for Arabic. This module
stays Qt-free: it is a plain string table plus an RTL predicate, testable on
headless CI where PySide6 is absent.

Conventions that the Phase 29 suite enforces:

* **Key parity.** Every key exists in every language. A test compares the key
  sets, so a half-translated screen cannot ship.
* **Named placeholders only.** ``{detail}``, ``{count}`` - never positional
  ``{}`` - so a translation cannot reorder the arguments by accident.
* **Technical identifiers stay untranslated.** Account codes (``401``),
  invoice numbers, SKUs, workflow states sent by the server and role names
  are values, not labels: they are interpolated verbatim and never passed
  through the catalogue.
"""

